       'RadioID',pRadioIDRx,...
       'CenterFrequency',pCenterFrequency,...
       'BasebandSampleRate',UE.cSampleRate,...
       'SamplesPerFrame', 2*rxLength,...
       'OutputDataType','double',...
       'UseCustomFilter',true,filtRxConfig{:}); 
resetPluto(gNBPluto,1);

