% Create a tx pluto object
load plutoTxFilter
UEPluto = sdrtx('Pluto','RadioID',pRadioIDTx,...
          'CenterFrequency',pCenterFrequency, ...
          'BasebandSampleRate',gNB.cSampleRate,'Gain',pGain,...
          'ShowAdvancedProperties',true,...
          'UseCustomFilter',true,filtTxConfig{:});

resetPluto(UEPluto,1);

